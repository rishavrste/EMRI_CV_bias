"""Markdown table of the 0PA-vs-1PA parameter bias: bias/sigma per parameter at each point's own
injected SNR, next to the 0PA best-fit overlap. Reads the Fisher_*.npy / SNR_*.npy files through
plot_bias.load_dataset (same Jacobi-preconditioned inversion as plot_bias.py), so every number
matches plot_bias.log. Writes bias_0PA_vs_1PA.md.

IMRI fits with overlap < SECONDARY_OVERLAP are flagged as probable secondary maxima.

Run (CPU):  python make_bias_table.py
"""
import os
import re

from parse_results import parse_all
from plot_bias import HERE, load_dataset

SYSTEMS = ("EMRI", "IMRI")
SHOWN = ["m1", "m2", "a", "p0", "e0", "Phi_phi0", "Phi_r0"]   # qS, phiS stay within +-0.5
SECONDARY_OVERLAP = 0.99
SUPERSEDED = {("IMRI", "idx1_dt5")}                          # replaced by IMRI grid_idx1
NOTES = {("EMRI", "grid_idx14"): "anomalous SNR, ignore"}


# --- one row ---------------------------------------------------------------
def z_scores(data):
    z = (data["bf"] - data["true"]) / data["sigma"]
    return dict(zip(data["param_names"], z))


def overlaps_0pa():
    """(system, point) -> 0PA best-fit overlap."""
    return {(c["system"], c["point"]): c["overlap"] for c in parse_all() if c["model"] == "0PA"}


def is_secondary(system, overlap):
    return system == "IMRI" and overlap < SECONDARY_OVERLAP


def row(system, point, data, ov):
    z = z_scores(data)
    note = NOTES.get((system, point), "")
    if is_secondary(system, ov):
        note = "probable secondary maximum"
    cells = [point.replace("grid_", ""), f"{data['snr0']:.2f}", f"{ov:.7f}"]
    cells += [f"{z[n]:+.2f}" for n in SHOWN] + [note]
    return "| " + " | ".join(cells) + " |"


# --- one system ------------------------------------------------------------
def point_key(point):
    """grid points in index order, then the named extra points."""
    m = re.fullmatch(r"grid_idx(\d+)", point)
    return (0, int(m.group(1)), "") if m else (1, 0, point)


def system_table(system):
    dataset, point_order, _ = load_dataset(system)
    ovs = overlaps_0pa()
    points = sorted((p for p in point_order
                     if (p, "0PA") in dataset and (system, p) not in SUPERSEDED), key=point_key)
    head = ["| point | SNR | 0PA overlap | " + " | ".join(SHOWN) + " | note |",
            "|---" * (len(SHOWN) + 4) + "|"]
    return head + [row(system, p, dataset[(p, "0PA")], ovs[(system, p)]) for p in points]


# --- the file --------------------------------------------------------------
INTRO = f"""# 0PA vs 1PA bias (Fisher_results)

Signal: 1PA (evolve_1PA on, 2PA off, no deviation). Template: 0PA. Each entry is
bias/sigma = (best fit - injection) / sigma, with sigma from the Fisher matrix at the best fit and
the point's own injected SNR. Source: `Fisher_*_0PA.npy`, `SNR_*.npy`; generated by
`make_bias_table.py` -- edit that, not this file.

- **No 0PA-vs-2PA bias exists in this repo.** Every Fisher here uses a 1PA signal; the 0PA-vs-2PA
  fits appear only as the `from_MAP` seeds, which come from the SK_files critical-SNR grid.
- **IMRI fits with 0PA overlap < {SECONDARY_OVERLAP} are probable secondary maxima** (the user's
  assessment, 2026-10-02, not yet verified by a re-climb): every other IMRI grid cell reaches
  >= 0.991. Their bias values may describe a secondary maximum rather than the true best fit.
  idx4 (0.9910) sits just above the threshold.
- **The Mahalanobis D in `plot_bias.log` is not usable.** It exceeds the direct bound 2 x SNR at
  every point (e.g. EMRI idx15: every |bias/sigma| < 0.15 but D = 234). The stored best fits carry
  9 significant figures and the Fisher condition numbers reach ~1e18, so rounding dominates D.
  The critical-SNR plots inherit this. The per-parameter bias/sigma below is unaffected.
- **1st-generation TDI, channels A, E and T** (fits and Fishers alike). To be redone with
  2nd-generation TDI, A and E only -- see `TDI_generation.md`.
- qS and phiS stay within +-0.5 sigma everywhere and are not shown.
"""


def main():
    parts = [INTRO]
    for system in SYSTEMS:
        parts += [f"\n## {system}\n", "\n".join(system_table(system)) + "\n"]
    out = os.path.join(HERE, "bias_0PA_vs_1PA.md")
    with open(out, "w") as f:
        f.write("".join(parts))
    print("".join(parts))
    print(f"[saved] {out}")


if __name__ == "__main__":
    main()
