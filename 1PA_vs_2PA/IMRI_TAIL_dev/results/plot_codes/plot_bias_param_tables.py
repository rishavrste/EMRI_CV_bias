"""1D bias of each parameter over the 25 grid points, one table per parameter.

    bias_1D_param_tables/snr{SNR}/{param}.png : bias / sigma on the (a, e0) grid, side by side:
        1PA-only (own sigma), 1PA + dev (own sigma), 1PA + dev in 1PA-only sigma; C_p and C_e have
        the 1PA + dev panel only. One colour scale per parameter (symmetric, its largest |bias/sigma|).
    bias_1D_param_tables/snr{SNR}/{param}.md  : the same 25 points copy-ready: bias = best fit -
        injection, sigma and bias / sigma for each template
all under results/plot/.

Run:  python plot_bias_param_tables.py [--snr 20]
"""
import argparse

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import TwoSlopeNorm

from bias_data import ALL, PHYS, load_bias
from common import (DIV, FLAG_NOTE, LABEL, SURFACE, TEXT_2, grid, ink_on, mark_flags, out_file,
                    style_axes)

LABEL = {**LABEL, "chi2": "χ2", "C_p": "C_p", "C_e": "C_e"}
PANELS = [("z_1pa", "1PA-only, own σ"), ("z_dev", "1PA + dev, own σ"),
          ("z_dev_1pa", "1PA + dev, in 1PA-only σ")]


def panels_for(name):
    return [(k, t) for k, t in PANELS if name in PHYS or k == "z_dev"]


def heat(ax, fig, pts, key, name, norm, title):
    z = grid(pts, lambda p: p[key][name]).astype(float)
    im = ax.imshow(z, origin="lower", cmap=DIV, norm=norm, aspect="auto")
    for (y, x), v in np.ndenumerate(z):
        ax.text(x, y, f"{v:+.3f}", ha="center", va="center", fontsize=8.5,
                color=ink_on(DIV(norm(v))))
    style_axes(ax, title)
    ax.set_facecolor(SURFACE)
    mark_flags(ax, pts)
    return im


def figure(pts, name, snr):
    panels = panels_for(name)
    lim = max(abs(p[k][name]) for p in pts for k, _ in panels)
    norm = TwoSlopeNorm(0.0, -lim, lim)
    fig, axes = plt.subplots(1, len(panels), figsize=(6.4 * len(panels), 5.6), facecolor=SURFACE,
                             squeeze=False)
    for ax, (key, title) in zip(axes[0], panels):
        im = heat(ax, fig, pts, key, name, norm, title)
    cb = fig.colorbar(im, ax=axes[0].tolist(), fraction=0.025, pad=0.02)
    cb.set_label(f"bias / σ  ({LABEL[name]})", color=TEXT_2)
    cb.outline.set_visible(False)
    fig.suptitle(f"IMRI_TAIL, 2PA signal: 1D bias of {LABEL[name]} at SNR {snr:g} "
                 "(best fit − injection, in units of the Fisher σ)", x=0.01, ha="left", fontsize=13)
    fig.text(0.01, 0.01, FLAG_NOTE, fontsize=8.5, color=TEXT_2)
    return fig


def markdown(pts, name, snr):
    has_1pa = name in PHYS
    head = ["idx", "a", "e0", "flag"]
    head += ["bias 1PA", "σ 1PA", "bias/σ 1PA"] if has_1pa else []
    head += ["bias dev", "σ dev", "bias/σ dev"] + (["bias dev / σ 1PA"] if has_1pa else [])
    lines = [f"# 1D bias of {name}, SNR {snr:g}", "",
             "Generated by results/plot_codes/plot_bias_param_tables.py. bias = best fit - injection "
             "(phases wrapped); σ from the Fisher matrix at each best fit (fisher_at_best.py).", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for p in pts:
        flag = ("M" if p["marginal"] else "") + ("S" if p["suspect"] else "")
        row = [str(p["idx"]), f"{p['a']:+.1f}", f"{p['e0']:.1f}", flag]
        if has_1pa:
            row += [f"{p['b_1pa'][name]:.6e}", f"{p['s_1pa'][name]:.6e}", f"{p['z_1pa'][name]:+.4f}"]
        row += [f"{p['b_dev'][name]:.6e}", f"{p['s_dev'][name]:.6e}", f"{p['z_dev'][name]:+.4f}"]
        row += [f"{p['z_dev_1pa'][name]:+.4f}"] if has_1pa else []
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--snr", type=float, default=20.0)
    args = ap.parse_args()
    pts = load_bias(args.snr)
    folder = ("bias_1D_param_tables", f"snr{args.snr:g}")
    for name in ALL:
        png = out_file(*folder, f"{name}.png")
        figure(pts, name, args.snr).savefig(png, dpi=160, facecolor=SURFACE, bbox_inches="tight")
        plt.close("all")
        out_file(*folder, f"{name}.md").write_text(markdown(pts, name, args.snr))
        print(f"-> {png} (+ .md)")


if __name__ == "__main__":
    main()
