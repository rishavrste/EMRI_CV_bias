"""Critical SNR per spin, 0PA vs 0PA + PN, as in EMRI_1PA_PN_DEV/plot_codes/plot_critical_snr.py:
    1D : rho_crit = SNR z_CL / |worst bias/sigma|, worst over the physical parameters (own sigma;
         for 0PA + PN, C_p and C_e marginalised and never the worst)
    nD : rho_crit = SNR D_CL / D,  D^2 = b^T Sigma_S^-1 b over the physical set S (C_p, C_e
         marginalised for 0PA + PN), D_CL^2 the chi^2_|S| quantile at CL
SNR = 20 (the stored Fishers); both measures scale with SNR, so rho_crit does not depend on it.
Each with the phases and with Phi_phi0, Phi_r0 left out (1D: not eligible; nD: marginalised).
    -> results/critical_snr.md, and the same tables in the terminal

Run (CPU):  python critical_snr.py
"""
import json

import numpy as np
from scipy import stats

import spin_config as S
from spin_config import C
from compare_bias import covariance                  # EMRI_1PA_PN_DEV/fisher: Jacobi-rescaled inverse

CLS = (0.90, 0.99)
NOPH = [n for n in C.PHYS if n not in C.PHASES]
VARIANTS = {"with phases": C.PHYS, "phases left out": NOPH}


def load(spin, template):
    """The highest-overlap Fisher among {template}_fisher.json and its tagged re-runs."""
    d = S.RESULTS / S.label(spin)
    runs = [json.loads(p.read_text()) | dict(run=p.name[:-len("_fisher.json")])
            for p in [d / f"{template}_fisher.json", *d.glob(f"{template}_*_fisher.json")]
            if p.exists()]
    if not runs:
        return None
    best = max(runs, key=lambda r: r["eval"]["overlap"])
    Sigma = covariance(np.array(best["fisher"]))
    return dict(best, Sigma=Sigma, b=dict(zip(best["names"], best["bias"])))


def z_scores(rec, subset):
    """bias_i / sigma_i over subset."""
    i = [rec["names"].index(n) for n in subset]
    return {n: rec["b"][n] / np.sqrt(rec["Sigma"][k, k]) for n, k in zip(subset, i)}


def nd_distance(rec, subset):
    k = [rec["names"].index(n) for n in subset]
    b = np.array([rec["b"][n] for n in subset])
    return float(np.sqrt(b @ np.linalg.solve(rec["Sigma"][np.ix_(k, k)], b)))


def critical(rec, subset, cl):
    """(1D rho_crit, its worst parameter, nD rho_crit) at confidence level cl."""
    z = z_scores(rec, subset)
    worst = max(z, key=lambda n: abs(z[n]))
    z_cl = stats.norm.ppf(0.5 + cl / 2)
    D_cl = np.sqrt(stats.chi2.ppf(cl, len(subset)))
    return S.SNR * z_cl / abs(z[worst]), worst, S.SNR * D_cl / nd_distance(rec, subset)


def fit_rows(recs):
    lines = ["| a | 0PA overlap | PN overlap | gain | C_p | C_e | runs used |", "|" + "---|" * 7]
    for spin, (r0, rp) in recs.items():
        o0, op = r0["eval"]["overlap"], rp["eval"]["overlap"]
        lines.append(f"| {spin:+g} | {o0:.10f} | {op:.10f} | {(1 - o0) / (1 - op):.3g} "
                     f"| {rp['b']['C_p']:+.4g} | {rp['b']['C_e']:+.4g} | {r0['run']}, {rp['run']} |")
    return lines


def crit_rows(recs, subset, cl):
    lines = [f"| a | 1D 0PA | 1D PN | nD 0PA | nD PN |", "|" + "---|" * 5]
    for spin, (r0, rp) in recs.items():
        c0, cp = critical(r0, subset, cl), critical(rp, subset, cl)
        lines.append(f"| {spin:+g} | {c0[0]:.4g} ({c0[1]}) | {cp[0]:.4g} ({cp[1]}) "
                     f"| {c0[2]:.4g} | {cp[2]:.4g} |")
    return lines


def main():
    recs, missing = {}, []
    for spin in sorted(S.SPINS):
        r0, rp = load(spin, "0pa"), load(spin, "pn")
        if r0 is None or rp is None:
            missing.append(S.label(spin))
            continue
        recs[spin] = (r0, rp)

    lines = ["# Spin check: critical SNR, 0PA vs 0PA + PN (idx22 injection, a varied)", "",
             "Generated by spin_check/critical_snr.py. p0: 1PA plunge at 2.5 yr; dist: SNR 20. "
             "1D: worst physical parameter (own sigma); nD: physical parameters, C_p and C_e "
             "marginalised for 0PA + PN. Below rho_crit the bias is hidden at that CL.", ""]
    if missing:
        lines += [f"Missing (no Fisher yet): {', '.join(missing)}", ""]
    lines += ["## Fits", ""] + fit_rows(recs) + [""]
    for vname, subset in VARIANTS.items():
        for cl in CLS:
            lines += [f"## {cl * 100:.0f}% CL, {vname}", ""] + crit_rows(recs, subset, cl) + [""]
    text = "\n".join(lines)
    (S.RESULTS / "critical_snr.md").write_text(text)
    print(text)
    print(f"-> {S.RESULTS / 'critical_snr.md'}")


if __name__ == "__main__":
    main()
