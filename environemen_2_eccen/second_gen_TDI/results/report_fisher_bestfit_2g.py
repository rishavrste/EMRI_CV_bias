"""Markdown report of fisher_bestfit_2g.json, compared with the 1st-gen SNR-200 re-score.

    python report_fisher_bestfit_2g.py   -> RESULTS.md

Overlap and bias tables are summary/report_fisher_bestfit.py's.  Added: the A / E SNR split
(no T channel in 2nd gen) and, per set and model, how far the 2nd-gen bias and sigma moved from
summary/fisher_bestfit_snr200.json.  CPU, seconds.
"""

import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "summary"))
from report_fisher_bestfit import MODELS, md_bias, md_overlap                   # noqa: E402

SECOND_GEN = os.path.join(HERE, "fisher_bestfit_2g.json")
FIRST_GEN = os.path.join(ROOT, "summary", "fisher_bestfit_snr200.json")


def md_setup(sets, first):
    rows = ["## Sets and SNR normalisation", "",
            "2nd-gen TDI, A and E only, band [1e-5, 0.05] Hz, dist moved to SNR 200.", "",
            "| set | e0 | SNR at native dist (2nd gen) | dist [Gpc] | dist 1st gen [Gpc] | "
            "dist / 1st gen | A share | E share |", "|---|---|---|---|---|---|---|---|"]
    for s in sets:
        ch = s["channel_snr"]
        tot = sum(v ** 2 for v in ch.values())
        d1 = first[s["tag"]]["dist"]
        rows.append(f"| {s['tag']} | {s['injection']['e0']:g} | {s['snr_native']:.3f} | "
                    f"{s['dist']:.6f} | {d1:.6f} | {s['dist'] / d1:.4f} | "
                    + " | ".join(f"{100 * ch[c] ** 2 / tot:.4f}%" for c in "AE") + " |")
    return rows + ["", "Share = fraction of SNR^2 carried by each channel.", ""]


def md_vs_first(sets, first):
    rows = ["## Change from 1st gen (summary/fisher_bestfit_snr200.json)", "",
            "Per model, the largest over the physical parameters (and C_p, C_e for PN).", "",
            "| set | model | overlap 2nd gen | overlap 1st gen | max abs((b2 - b1) / sigma1) | "
            "max abs(sigma2 / sigma1 - 1) |", "|---|---|---|---|---|---|"]
    for s in sets:
        for t, label in MODELS:
            m, m1 = s["models"][t], first[s["tag"]]["models"][t]
            s1 = np.array(m1["sigma"])
            db = np.max(np.abs((np.array(m["bias"]) - np.array(m1["bias"])) / s1))
            ds = np.max(np.abs(np.array(m["sigma"]) / s1 - 1))
            rows.append(f"| {s['tag']} | {label} | {m['overlap']:.12f} | {m1['overlap']:.12f} | "
                        f"{db:.3e} | {ds:.3e} |")
    return rows + [""]


def main():
    sets = json.load(open(SECOND_GEN))
    first = {s["tag"]: s for s in json.load(open(FIRST_GEN))}
    lines = ["# Fisher / overlap re-score at the 2nd-gen TDI best fits (SNR 200)", "",
             "Generated by `report_fisher_bestfit_2g.py` from `fisher_bestfit_2g.json` "
             "-- do not hand-edit.", ""]
    lines += md_setup(sets, first) + md_overlap(sets) + md_bias(sets) + md_vs_first(sets, first)
    out = os.path.join(HERE, "RESULTS.md")
    open(out, "w").write("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
